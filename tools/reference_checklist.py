"""Reference verification checklist, generated from ``paper/references.bib``.

    python tools/reference_checklist.py [--out paper/verification_checklist.md]

The bibliography records, in each entry's ``annote``, how far its identity was confirmed (V1 core
fields confirmed in retrieved extracts, V2 some fields from memory, V3 author-supplied BibTeX).
No entry has been checked against a publisher record, because the publishers' sites were not
reachable from the authoring environment. This tool turns that into a work list. It never marks an
entry verified: that is a human act with the publisher record open. It also lists works the
economic-evaluation chapter will need that are *not* in the bibliography; those are names recalled
from memory, they are unverified, and they must not be cited until someone has found them.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Recalled from memory by the authoring assistant; NOT in the bibliography; NOT verified.
PLANNED_NOT_IN_BIB = [
    ("Drummond et al., Methods for the Economic Evaluation of Health Care Programmes (4th ed.)",
     "cost-effectiveness and cost-minimisation analysis, perspective, dominance"),
    ("Briggs and O'Brien, 'The death of cost-minimization analysis?' (Health Economics, 2001)",
     "a cost comparison needs demonstrated equivalence of effect"),
    ("Husereau et al., CHEERS 2022 reporting statement",
     "what an economic evaluation must state: perspective, price year, currency, uncertainty"),
    ("Drummond and Sculpher, 'Common methodological flaws in economic evaluations' (2005)",
     "selective comparators and prices"),
    ("Briggs and Fenn, and Willan and Briggs, on uncertainty in cost-effectiveness ratios",
     "ratio uncertainty"),
    ("Briggs, Sculpher and Claxton, Decision Modelling for Health Economic Evaluation (2006)",
     "one-way and threshold analysis"),
    ("Efron and Tibshirani, An Introduction to the Bootstrap (1993); DiCiccio and Efron 1996",
     "bootstrap and the BCa interval already committed to in blueprint section 29"),
    ("Boardman et al., Cost-Benefit Analysis (opportunity cost of labour)", "valuing labour time"),
    ("Jorgensen and Shepperd, systematic review of software cost estimation (IEEE TSE, 2007)",
     "reliability of effort estimates, for the build view"),
    ("Anderson and Moore, 'The economics of information security' (Science, 2006)",
     "security economics framing"),
    ("Nosek et al., 'The preregistration revolution' (PNAS, 2018)", "pre-registration"),
    ("Strubell et al. 2019; Luccioni et al. 2023; Samsi et al. 2023", "energy of language-model "
     "inference"),
    ("Irugalbandara et al., on replacing a paid language-model API with open models (2024)",
     "cost-benefit of local versus hosted models"),
]


def parse(text: str) -> list[dict[str, str]]:
    entries = []
    for m in re.finditer(r"@(\w+)\{([^,\s]+),(.*?)\n\}", text, flags=re.S):
        body = m.group(3)
        fields = {k.lower(): re.sub(r"\s+", " ", v).strip() for k, v in
                  re.findall(r"(\w+)\s*=\s*\{((?:[^{}]|\{[^{}]*\})*)\}", body, flags=re.S)}
        entries.append({"key": m.group(2), "type": m.group(1), **fields})
    return entries


def level(annote: str) -> str:
    m = re.match(r"\s*(V\d)", annote or "")
    return m.group(1) if m else "unlabelled"


def caveat(annote: str) -> str:
    return re.sub(r"^\s*V\d:?\s*", "", annote or "").strip()


def render(entries: list[dict[str, str]]) -> str:
    by: dict[str, list[dict[str, str]]] = {}
    for e in entries:
        by.setdefault(level(e.get("annote", "")), []).append(e)
    L = ["# Reference verification checklist", "",
         "Generated by `tools/reference_checklist.py` from `paper/references.bib`. **No entry has "
         "been checked against a publisher record**; the publishers' sites were not reachable "
         "from the authoring environment. Tick an item only with the publisher record open, and "
         "write who and when. Nothing below is marked verified.", "",
         f"Entries: {len(entries)}. " + ", ".join(f"{k}: {len(v)}" for k, v in sorted(by.items())),
         "", "How to read the levels: V1 = authors, title, venue, year confirmed in retrieved "
         "extracts; V2 = some fields recalled from memory or inferred; V3 = author-supplied "
         "BibTeX.", ""]
    for lv in sorted(by):
        L += [f"## {lv}", "",
              "| key | title | note recorded when it was assessed | publisher record checked |",
              "|---|---|---|---|"]
        for e in sorted(by[lv], key=lambda x: x["key"]):
            t = e.get("title", "").replace("|", "/")[:90]
            note = caveat(e.get("annote", ""))[:240] or "no caveat recorded"
            L.append(f"| `{e['key']}` | {t} | {note} | [ ] pending |")
        L.append("")
    full = [e for e in entries if re.search(r"full text not read|findings were not retrieved",
                                            e.get("annote", ""), re.I)]
    L += ["## Closest prior work: full text must be read before the thesis claims anything about "
          "it", ""]
    L += [f"- `{e['key']}`: {e.get('title', '')[:100]}" for e in sorted(full,
                                                                        key=lambda x: x["key"])]
    L += ["", "## Works the economic-evaluation chapter will need that are NOT in the bibliography",
          "", "Recalled from memory; **unverified; do not cite** until found and read, then add "
          "to the bibliography with the level actually reached.", ""]
    L += [f"- [ ] {t}: {why}" for t, why in PLANNED_NOT_IN_BIB]
    L += ["", "## Also", "", "- Repeat the literature search for 2026 before submission (the "
          "field moves quickly).", "- Vendor price pages are data for the price register, not "
          "literature; never cite them as evidence of savings.", ""]
    return "\n".join(L)


def main(argv: list[str]) -> int:
    entries = parse((ROOT / "paper" / "references.bib").read_text(encoding="utf-8"))
    text = render(entries)
    if "--out" in argv:
        Path(argv[argv.index("--out") + 1]).write_text(text, encoding="utf-8")
        print(f"{len(entries)} entries")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
