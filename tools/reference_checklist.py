"""Reference verification checklist, generated from ``paper/references.bib`` and
``paper/verification_records.yaml``.

    python tools/reference_checklist.py [--out paper/verification_checklist.md]

Each bibliography entry's ``annote`` states the level its identity was checked to: ``P`` (the source
itself was read: a software README or documentation), ``E-A`` (identity and abstract-level content
confirmed through search-engine extracts) or ``E-M`` (bibliographic data only, through extracts).
The verification record holds what was found, the discrepancies and which thesis sentences the
source supports. The authoring environment's network policy blocks publisher sites, DOI
resolution and arXiv, so no paper has been read in full: this tool marks every paper
"Full-text verification pending" and never marks anything as fully verified. That is a human act
with the paper open. It also lists works the economic-evaluation chapter may need that are *not*
in the bibliography; those are names recalled from memory, unverified, and must not be cited
until someone has found them.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Recalled from memory by the authoring assistant; NOT in the bibliography; NOT verified.
PLANNED_NOT_IN_BIB = [
    ("Drummond et al., Methods for the Economic Evaluation of Health Care Programmes (4th ed.)",
     "cost-effectiveness and cost-minimisation analysis, perspective, dominance"),
    ("Briggs and O'Brien, 'The death of cost-minimization analysis?' (Health Economics, 2001)",
     "a cost comparison needs demonstrated equivalence of effect"),
    ("Husereau et al., CHEERS 2022 reporting statement",
     "what an economic evaluation must state: perspective, price year, currency, uncertainty"),
    ("Drummond and Sculpher, 'Common methodological flaws in economic evaluations' (2005)",
     "selective comparators and prices"),
    ("Briggs and Fenn, and Willan and Briggs, on uncertainty in cost-effectiveness ratios",
     "ratio uncertainty"),
    ("Briggs, Sculpher and Claxton, Decision Modelling for Health Economic Evaluation (2006)",
     "one-way and threshold analysis"),
    ("Efron and Tibshirani, An Introduction to the Bootstrap (1993); DiCiccio and Efron 1996",
     "bootstrap and the BCa interval already committed to in blueprint section 29"),
    ("Boardman et al., Cost-Benefit Analysis (opportunity cost of labour)", "valuing labour time"),
    ("Jorgensen and Shepperd, systematic review of software cost estimation (IEEE TSE, 2007)",
     "reliability of effort estimates, for the build view"),
    ("Anderson and Moore, 'The economics of information security' (Science, 2006)",
     "security economics framing"),
    ("Nosek et al., 'The preregistration revolution' (PNAS, 2018)", "pre-registration"),
    ("Strubell et al. 2019; Luccioni et al. 2023; Samsi et al. 2023", "energy of language-model "
     "inference"),
    ("Irugalbandara et al., on replacing a paid language-model API with open models (2024)",
     "cost-benefit of local versus hosted models"),
]


def parse(text: str) -> list[dict[str, str]]:
    entries = []
    for m in re.finditer(r"@(\w+)\{([^,\s]+),(.*?)\n\}", text, flags=re.S):
        body = m.group(3)
        fields = {k.lower(): re.sub(r"\s+", " ", v).strip() for k, v in
                  re.findall(r"(\w+)\s*=\s*\{((?:[^{}]|\{[^{}]*\})*)\}", body, flags=re.S)}
        entries.append({"key": m.group(2), "type": m.group(1), **fields})
    return entries


LEVELS = {"P": "source read directly (README or documentation; not a paper)",
          "E-A": "identity and abstract-level content confirmed through search extracts",
          "E-M": "bibliographic data confirmed through search extracts only"}
FULL_TEXT_PENDING = "Full-text verification pending"


def level(annote: str) -> str:
    m = re.match(r"\s*(P|E-A|E-M)\b", annote or "")
    return m.group(1) if m else "unlabelled"


def caveat(annote: str) -> str:
    return re.sub(r"^\s*(P|E-A|E-M):?\s*", "", annote or "").strip()


def load_records(path: Path) -> dict[str, dict]:
    if not path.exists():
        return {}
    import yaml
    return {r["key"]: r for r in yaml.safe_load(path.read_text(encoding="utf-8"))["records"]}


def render(entries: list[dict[str, str]], records: dict[str, dict] | None = None) -> str:
    records = records or {}
    by: dict[str, list[dict[str, str]]] = {}
    for e in entries:
        by.setdefault(level(e.get("annote", "")), []).append(e)
    L = ["# Reference verification checklist", "",
         "Generated by `tools/reference_checklist.py` from `paper/references.bib` and "
         "`paper/verification_records.yaml`. Papers were checked only through search-engine "
         "extracts, because the authoring environment's network policy blocks publisher sites, "
         "DOI resolution and arXiv. **No paper has been checked against its full text; every paper "
         f"below is marked \"{FULL_TEXT_PENDING}\".** Software and documentation sources hosted on "
         "GitHub were read directly. Tick the last column only with the full text open, and write "
         "who and when.", "",
         f"Entries: {len(entries)}. " + ", ".join(f"{k}: {len(v)}" for k, v in sorted(by.items())),
         "", "Levels: " + "; ".join(f"**{k}** = {v}" for k, v in LEVELS.items()) + ".", ""]
    for lv in [x for x in ("P", "E-A", "E-M") if x in by] + [x for x in by if x not in LEVELS]:
        L += [f"## {lv}: {LEVELS.get(lv, 'unlabelled')}", "",
              "| key | title | checked | discrepancies | claims needing the full text | "
              "full text |", "|---|---|---|---|---|---|"]
        for e in sorted(by[lv], key=lambda x: x["key"]):
            r = records.get(e["key"], {})
            t = e.get("title", "").replace("|", "/")[:80]
            disc = len(r.get("discrepancies", []))
            needs = sum(1 for c in r.get("claim_checks", [])
                        if c.get("status") in ("needs_full_text", "partly_supported",
                                               "contradicted_by_extract"))
            ft = "n/a (not a paper) [x] read" if lv == "P" else f"[ ] {FULL_TEXT_PENDING}"
            L.append(f"| `{e['key']}` | {t} | {r.get('checked_on', '?')} | {disc} | {needs} | "
                     f"{ft} |")
        L.append("")
    flagged = [(k, c) for k, r in sorted(records.items()) for c in r.get("claim_checks", [])
               if c.get("status") in ("needs_full_text", "partly_supported",
                                      "contradicted_by_extract")]
    L += ["## Thesis sentences the extracts did not fully support", "",
          "Each must be checked against the full text, or reworded to what the extracts show.", ""]
    L += [f"- `{k}` ({c['status']}): {c.get('excerpt', '')[:160]}" for k, c in flagged]
    L += ["", "## Works the economic-evaluation chapter may need that are NOT in the bibliography",
          "", "Recalled from memory; **unverified; do not cite** until found and read, then add "
          "to the bibliography with the level actually reached.", ""]
    L += [f"- [ ] {t}: {why}" for t, why in PLANNED_NOT_IN_BIB]
    L += ["", "## Also", "", "- Repeat the literature search shortly before submission (the "
          "field moves quickly).", "- Vendor price pages are data for the price register, not "
          "literature; never cite them as evidence of savings.", ""]
    return "\n".join(L)


def main(argv: list[str]) -> int:
    entries = parse((ROOT / "paper" / "references.bib").read_text(encoding="utf-8"))
    text = render(entries, load_records(ROOT / "paper" / "verification_records.yaml"))
    if "--out" in argv:
        Path(argv[argv.index("--out") + 1]).write_text(text, encoding="utf-8")
        print(f"{len(entries)} entries")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
