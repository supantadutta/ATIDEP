"""Related-work comparison matrix, rendered from ``paper/related_work.yaml``.

    python tools/related_work_matrix.py [--data paper/related_work.yaml]
                                        [--out paper/related_work_matrix.md]

Every cell is one of ``Yes``, ``Partial``, ``No`` or ``Not reported``. A cell other than
``Not reported`` must carry the evidence for it (what the source says) and the source it came
from; the loader refuses one that does not, so a capability can never be marked present (or
absent) by inference. ``No`` means the source says so; silence is ``Not reported``. Each row also
records how far the source was read (abstract or metadata through search extracts, or full text);
nothing read only through extracts is presented as a full-text reading.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
VALUES = ("Yes", "Partial", "No", "Not reported")
SHORT = {"Yes": "Y", "Partial": "P", "No": "N", "Not reported": "–"}
COLUMNS = [
    ("cti_ingestion", "CTI ingestion"),
    ("structured_extraction", "Structured extraction"),
    ("ioc_generation", "IOC generation"),
    ("behavioural_detection", "Behavioural detection"),
    ("rule_generation", "Sigma / rule generation"),
    ("deterministic_validation", "Deterministic validation"),
    ("adversarial_evaluation", "Adversarial / prompt-injection evaluation"),
    ("human_approval", "Human approval / governance"),
    ("deployment_rollback", "Deployment / rollback"),
    ("feedback_improvement", "Feedback / improvement"),
    ("analyst_effort", "Analyst-effort measurement"),
    ("economic_analysis", "Economic / cost analysis"),
    ("open_source", "Open-source availability"),
]
LEVELS = ("full_text", "primary_source_read", "abstract_via_search_extract",
          "metadata_via_search_extract")


class MatrixError(ValueError):
    pass


def validate(rows: list[dict[str, Any]], bib_keys: set[str] | None = None) -> None:
    seen: set[str] = set()
    for r in rows:
        key = r.get("key")
        if not key or key in seen:
            raise MatrixError(f"missing or duplicate key: {key!r}")
        seen.add(key)
        if bib_keys is not None and key not in bib_keys:
            raise MatrixError(f"{key}: not in the bibliography")
        if r.get("level") not in LEVELS:
            raise MatrixError(f"{key}: level must be one of {LEVELS}")
        for col, _ in COLUMNS:
            cell = (r.get("cells") or {}).get(col)
            if not isinstance(cell, dict) or cell.get("value") not in VALUES:
                raise MatrixError(f"{key}.{col}: value must be one of {VALUES}")
            if cell["value"] != "Not reported":
                if not str(cell.get("evidence", "")).strip() or not str(
                        cell.get("source", "")).strip():
                    raise MatrixError(
                        f"{key}.{col}: '{cell['value']}' needs evidence and a source")
        for f in ("year", "name", "relevance", "limitation"):
            if not str(r.get(f, "")).strip():
                raise MatrixError(f"{key}: {f} is required")


def load(path: Path, bib: Path | None = None) -> dict[str, Any]:
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    keys = None
    if bib is not None and bib.exists():
        import re
        keys = set(re.findall(r"^@\w+\{([^,]+),", bib.read_text(encoding="utf-8"), flags=re.M))
    validate(data["rows"], keys)
    return data


def _esc(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


BEGIN = "<!-- MATRIX:BEGIN (generated by tools/related_work_matrix.py) -->"
END = "<!-- MATRIX:END -->"
READ = {"full_text": "F", "primary_source_read": "R", "abstract_via_search_extract": "A",
        "metadata_via_search_extract": "M"}


def render_table(data: dict[str, Any], caption: str = "",
                 keys: list[str] | None = None) -> str:
    """The compact table for a chapter: rows (all, or those in ``keys``), the ATIDEP design row
    and the column key. Columns are M1-M13 so as not to be confused with components C1-C5."""
    head = ["Work", "Year"] + [f"M{i}" for i in range(1, len(COLUMNS) + 1)] + ["Read"]
    rows = data["rows"]
    if keys is not None:
        unknown = sorted(set(keys) - {r["key"] for r in rows})
        if unknown:
            raise MatrixError(f"keys not in the matrix data: {unknown}")
        rows = [r for r in rows if r["key"] in keys]
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for r in rows:
        out.append(f"| {_esc(r['name'])} [@{r['key']}] | {r['year']} | "
                   + " | ".join(SHORT[r["cells"][c]["value"]] for c, _ in COLUMNS)
                   + f" | {READ[r['level']]} |")
    if data.get("atidep"):
        out.append("| **ATIDEP (design, not a result)** | 2026 | "
                   + " | ".join(SHORT[data["atidep"][c]] for c, _ in COLUMNS) + " | – |")
    if caption:
        out += ["", f": {caption}"]
    out += ["", "Columns: " + "; ".join(f"M{i} {label}" for i, (_, label) in
                                       enumerate(COLUMNS, 1))
            + ". Y = yes, P = partial, N = no (the source says so), – = not reported in the "
              "source as read. Read: A = abstract-level search extracts, M = metadata only, R = "
              "software README read directly, F = full text. No row has been checked against a "
              "full text. Evidence for every marked cell: `paper/related_work_matrix.md`."]
    return "\n".join(out)


def sync_chapter(path: Path, data: dict[str, Any], caption: str,
                 keys: list[str] | None = None) -> bool:
    """Replace the table between the markers in a file; True if the file changed."""
    text = path.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        raise MatrixError(f"{path}: matrix markers not found")
    a, b = text.index(BEGIN) + len(BEGIN), text.index(END)
    new = text[:a] + "\n" + render_table(data, caption, keys) + "\n" + text[b:]
    if new != text:
        path.write_text(new, encoding="utf-8")
    return new != text


CHAPTER_CAPTION = ("Table 2.10. Related-work comparison matrix (capabilities stated in the "
                   "sources as read).")
# The closest works, shown in the supervisor brief; the full matrix is Table 2.10.
BRIEF_KEYS = ["cai2026sigmerge", "ghaffarzadegan2026autosigma", "schwartz2024llmcloudhunter",
              "mitra2025falcon", "chakraborty2026ctirealm", "schafhauzer2026context",
              "tyagi2026sigmalint", "zshguy2026tyrian", "cheng2026ttprint",
              "valletta2026tracecti"]
BRIEF_CAPTION = ("Preliminary comparison with the closest works (a subset of Table 2.10 of the "
                 "paper).")


def render(data: dict[str, Any]) -> str:
    rows = data["rows"]
    head = ["Work", "Year"] + [f"M{i}" for i in range(1, len(COLUMNS) + 1)] + ["Read"]
    out = [
        "# Related-work comparison matrix",
        "",
        "Generated by `tools/related_work_matrix.py` from `paper/related_work.yaml`; edit the "
        "YAML, not this file.",
        "",
        data.get("preamble", "").strip(),
        "",
        "Cell values: **Y** = Yes, **P** = Partial, **N** = No (the source says so), "
        "**–** = Not reported (the source, as read, does not say). A Y, P or N is shown only "
        "where the evidence in the appendix supports it. *Read*: A = abstract-level content "
        "through search extracts, M = metadata only through search extracts, R = a software "
        "README read directly (not a paper), F = full text of a paper. "
        "**No row has been checked against the full text; full-text verification is pending for "
        "every row.**",
        "",
        "Columns: " + "; ".join(f"M{i} {label}" for i, (_, label) in enumerate(COLUMNS, 1)) + ".",
        "",
        "| " + " | ".join(head) + " |",
        "|" + "---|" * len(head),
    ]
    read = READ
    for r in rows:
        cells = [SHORT[r["cells"][c]["value"]] for c, _ in COLUMNS]
        out.append(f"| {_esc(r['name'])} [@{r['key']}] | {r['year']} | " + " | ".join(cells)
                   + f" | {read[r['level']]} |")
    if data.get("atidep"):
        a = data["atidep"]
        out += ["", "**ATIDEP (this thesis), by design.** The row states what ATIDEP is built to "
                "do; whether it does so well is what Chapters 7 and 8 evaluate.", "",
                "| " + " | ".join(head[2:-1]) + " |", "|" + "---|" * len(COLUMNS),
                "| " + " | ".join(SHORT[a[c]] for c, _ in COLUMNS) + " |"]
    out += ["", "## Relevance and remaining gap", "", "| Work | Relevance to ATIDEP | "
            "Limitation relative to ATIDEP's problem |", "|---|---|---|"]
    out += [f"| {_esc(r['name'])} [@{r['key']}] | {_esc(r['relevance'])} | "
            f"{_esc(r['limitation'])} |" for r in rows]
    out += ["", "## Evidence for each marked cell", ""]
    for r in rows:
        marked = [(label, r["cells"][c]) for c, label in COLUMNS
                  if r["cells"][c]["value"] != "Not reported"]
        out.append(f"**{_esc(r['name'])}** [@{r['key']}] ({read[r['level']]}; "
                   f"{_esc(r.get('read_note', 'full-text verification pending'))})")
        out.append("")
        if not marked:
            out.append("- no capability marked; every cell is Not reported")
        for label, cell in marked:
            out.append(f"- *{label}*: {cell['value']}. {_esc(cell['evidence'])} "
                       f"(source: {_esc(cell['source'])})")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--data", default=str(ROOT / "paper" / "related_work.yaml"))
    ap.add_argument("--bib", default=str(ROOT / "paper" / "references.bib"))
    ap.add_argument("--out", default=str(ROOT / "paper" / "related_work_matrix.md"))
    ap.add_argument("--chapter", default=str(ROOT / "paper" / "chapters" /
                                              "02_literature_review.md"))
    ap.add_argument("--brief", default=str(ROOT / "docs" / "supervisor_brief.md"))
    a = ap.parse_args(argv)
    data = load(Path(a.data), Path(a.bib))
    Path(a.out).write_text(render(data), encoding="utf-8")
    for path, caption, keys in ((Path(a.chapter), CHAPTER_CAPTION, None),
                                (Path(a.brief), BRIEF_CAPTION, BRIEF_KEYS)):
        if path.exists() and BEGIN in path.read_text(encoding="utf-8"):
            sync_chapter(path, data, caption, keys)
    print(f"{len(data['rows'])} rows written to {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
