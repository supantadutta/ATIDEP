"""Resolve ``requirements.in`` to exact pins from the installed environment.

    python tools/make_lock.py [--write]

Walks the dependency graph of every direct requirement through the installed package metadata
(honouring environment markers), and prints, or with ``--write`` writes, ``requirements.txt``.
The pins are those of the environment the tests ran in. Wheel hashes are not recorded; install
with ``pip install -r requirements.txt`` into a clean virtual environment to reproduce.
"""

from __future__ import annotations

import re
import sys
from importlib.metadata import PackageNotFoundError, distribution, requires
from pathlib import Path

from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[1]


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def direct(path: Path) -> list[str]:
    out = []
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            out.append(line)
    return out


def closure(names: list[str]) -> tuple[dict[str, str], list[str]]:
    seen: dict[str, str] = {}
    missing: list[str] = []

    def visit(name: str) -> None:
        n = norm(name)
        if n in seen:
            return
        try:
            dist = distribution(n)
        except PackageNotFoundError:
            missing.append(n)
            return
        seen[n] = dist.version
        for raw in requires(n) or []:
            req = Requirement(raw)
            if req.marker is not None and not req.marker.evaluate({"extra": ""}):
                continue
            visit(req.name)

    for n in names:
        visit(Requirement(n).name)
    return seen, missing


def render(pins: dict[str, str], direct_names: list[str]) -> str:
    top = {norm(Requirement(n).name) for n in direct_names}
    lines = ["# Generated by tools/make_lock.py from requirements.in. Do not edit by hand.",
             "# Exact versions of the environment the tests ran in (no wheel hashes).", ""]
    for name in sorted(pins):
        mark = "  # direct" if name in top else ""
        lines.append(f"{name}=={pins[name]}{mark}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    names = direct(ROOT / "requirements.in")
    pins, missing = closure(names)
    if missing:
        print("not installed: " + ", ".join(sorted(set(missing))), file=sys.stderr)
        return 1
    text = render(pins, names)
    if "--write" in argv:
        (ROOT / "requirements.txt").write_text(text)
        print(f"wrote requirements.txt ({len(pins)} pins)")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
